// Keep standalone HTML pages as the source of truth; bundle their content for file:// navigation.
const fs = require('node:fs');
const path = require('node:path');
const root = path.join(__dirname, '..');
const pages = {};
for (const name of fs.readdirSync(root).filter(name => name.endsWith('.html')).sort()) {
  const html = fs.readFileSync(path.join(root, name), 'utf8');
  const main = html.match(/<main\b[\s\S]*?<\/main>/)?.[0];
  const page = html.match(/<body[^>]*data-page="([^"]+)"/)?.[1];
  const title = html.match(/<title>([\s\S]*?)<\/title>/)?.[1];
  const description = html.match(/<meta name="description" content="([^"]*)"/)?.[1] || '';
  if (!main || !page || !title) throw new Error('Missing page metadata: ' + name);
  pages[name] = { page, title, description, main };
}
const output = '// Generated by node site-v2/scripts/build-page-templates.cjs. Edit the HTML sources.\n' +
  'window.SITE_PAGES = ' + JSON.stringify(pages, null, 2) + ';\n';
const target = path.join(root, 'assets/js/page-templates.js');
if (process.argv.includes('--check')) {
  if (fs.readFileSync(target, 'utf8') !== output) throw new Error('Page templates are stale; run the generator.');
} else fs.writeFileSync(target, output);
